function withCatalogMetadata(products: HomeProduct[], catalogCategory: string): HomeProduct[] {
  const catalogProducts = productCatalog.filter(
    (product) => product.collection === "category" && product.category === catalogCategory
  );

  return products.map((product, index) => {
    const catalogProduct = catalogProducts[index];

    if (!catalogProduct) {
      return product;
    }

    return {
      ...product,
      id: catalogProduct.id,
      name: catalogProduct.name,
      detail: catalogProduct.detail ?? catalogProduct.displayUnit,
      price: catalogProduct.price,
      oldPrice: catalogProduct.oldPrice ?? undefined
    };
  });
}

